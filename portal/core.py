def topic_terms(tokens, df, ntotal, k=4):
    """Top-k distinctive terms for a session by tf-idf, skipping stopwords/noise.
    Drops any token containing a digit (id fragments like 'bc2c', '1097')."""
    import math
    from collections import Counter
    tf = Counter(t for t in tokens
                 if len(t) >= 3 and t not in _STOP
                 and not any(c.isdigit() for c in t))
    scored = []
    for w, f in tf.items():
        d = df.get(w, 1)
        if d >= max(3, ntotal // 2):     # skip terms common across the corpus
            continue
        idf = math.log(1 + ntotal / d)
        scored.append((f * idf, w))
    scored.sort(reverse=True)
    return [w for _, w in scored[:k]]
