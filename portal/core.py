def model_label(raw):
    """Short human label for a raw model id. Unknown/None/synthetic -> 'unknown'."""
    if not raw:
        return "unknown"
    r = str(raw).lower()
    if r.startswith("<") or r == "synthetic":
        return "unknown"
    for key, label in _MODEL_MAP:
        if key in r:
            return label
    return str(raw)[:18]


