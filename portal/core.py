TYPE_GLYPH = {"build": "◆", "fix": "✳", "rsrch": "◎", "comms": "✉",
              "setup": "⚙", "data": "▤", "·": "·"}


def classify_type(title, search, edits=0):
    hay = (" " + " ".join(toks(title) * 2 + toks(search)) + " ")
    scores = {}
    for name, kws in _TYPE_RULES:
        scores[name] = sum(1 for k in kws if (" " + k + " ") in hay)
    best = max(scores, key=lambda n: scores[n]) if any(scores.values()) else None
    if not best:
        return "build" if edits >= 3 else "·"
    return best


